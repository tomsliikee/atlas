//! CREATE statements written from the schema model: for the structure view,
//! for backups, and as the target of migrations and designs.
//!
//! Types are written as the source database spells them. A schema read from
//! MariaDB and written as PostgreSQL DDL therefore keeps MariaDB types; Atlas
//! does not translate between dialects.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::schema::{Column, Index, Relation, RelationKind, Schema, Table, TableKind};
use crate::sql::{Dialect, ident, quoted};

/// The column part of a CREATE TABLE line, without a trailing comma.
/// `inline_pk` adds `PRIMARY KEY` (used for SQLite's rowid alias).
pub fn column_def(dialect: Dialect, column: &Column, inline_pk: bool) -> String {
    let mut out = ident(dialect, &column.name);
    out.push(' ');
    let identity = column.auto_increment && dialect == Dialect::Postgres;
    let data_type = if column.data_type.trim().is_empty() { "text" } else { column.data_type.trim() };
    // SERIAL needs a sequence that a fresh database does not have; an
    // identity column brings its own.
    let data_type = match data_type.to_ascii_lowercase().as_str() {
        "serial" => "integer",
        "bigserial" => "bigint",
        "smallserial" => "smallint",
        _ => data_type,
    };
    out.push_str(data_type);
    if let Some(expr) = &column.generated {
        match dialect {
            Dialect::MySql => {
                let _ = write!(out, " AS ({expr})");
            }
            Dialect::Postgres => {
                let _ = write!(out, " GENERATED ALWAYS AS ({expr}) STORED");
            }
            Dialect::Sqlite => {
                let _ = write!(out, " GENERATED ALWAYS AS ({expr})");
            }
        }
    }
    if identity {
        out.push_str(" GENERATED BY DEFAULT AS IDENTITY");
    }
    if !column.nullable || column.primary {
        out.push_str(" NOT NULL");
    }
    if let Some(default) = column.default.as_deref().map(str::trim)
        && !default.is_empty()
        && !default.eq_ignore_ascii_case("null")
        && column.generated.is_none()
        // A sequence default only makes sense in the database it came from.
        && !(identity || default.starts_with("nextval("))
    {
        let _ = write!(out, " DEFAULT {default}");
    }
    if inline_pk {
        out.push_str(" PRIMARY KEY");
        if column.auto_increment && dialect == Dialect::Sqlite {
            out.push_str(" AUTOINCREMENT");
        }
    }
    if column.auto_increment && dialect == Dialect::MySql {
        out.push_str(" AUTO_INCREMENT");
    }
    if dialect == Dialect::MySql
        && let Some(comment) = &column.comment
        && !comment.is_empty()
    {
        let _ = write!(out, " COMMENT {}", quoted(dialect, comment));
    }
    out
}

/// `CONSTRAINT name FOREIGN KEY (…) REFERENCES …` for a declared relation.
pub fn foreign_key(dialect: Dialect, relation: &Relation) -> String {
    let cols = |c: &[String]| c.iter().map(|c| ident(dialect, c)).collect::<Vec<_>>().join(", ");
    let mut out = String::new();
    if let Some(name) = relation.name.as_deref().filter(|n| !n.is_empty()) {
        let _ = write!(out, "CONSTRAINT {} ", ident(dialect, name));
    }
    let _ = write!(
        out,
        "FOREIGN KEY ({}) REFERENCES {} ({})",
        cols(&relation.from_columns),
        ident(dialect, &relation.to_table),
        cols(&relation.to_columns)
    );
    if let Some(a) = relation.on_delete {
        let _ = write!(out, " ON DELETE {}", a.sql());
    }
    if let Some(a) = relation.on_update {
        let _ = write!(out, " ON UPDATE {}", a.sql());
    }
    out
}

/// SQLite only treats `INTEGER PRIMARY KEY` written on the column as the
/// rowid; keep that form when the key is a single integer column.
fn sqlite_rowid(dialect: Dialect, table: &Table) -> Option<&str> {
    if dialect != Dialect::Sqlite {
        return None;
    }
    match table.primary_key().as_slice() {
        [one] => table.column(one).filter(|c| c.data_type.eq_ignore_ascii_case("integer")).map(|c| c.name.as_str()),
        _ => None,
    }
}

/// `CREATE TABLE`, with the foreign keys of `relations` that start at this
/// table when `with_fks` is set.
pub fn create_table(dialect: Dialect, table: &Table, relations: &[Relation], with_fks: bool) -> String {
    if table.kind == TableKind::View {
        return create_view(dialect, table);
    }
    let rowid = sqlite_rowid(dialect, table);
    let mut lines: Vec<String> =
        table.columns.iter().map(|c| column_def(dialect, c, rowid == Some(c.name.as_str()))).collect();
    let pk = table.primary_key();
    if !pk.is_empty() && rowid.is_none() {
        let cols: Vec<String> = pk.iter().map(|c| ident(dialect, c)).collect();
        lines.push(format!("PRIMARY KEY ({})", cols.join(", ")));
    }
    for set in &table.unique {
        let cols: Vec<String> = set.iter().map(|c| ident(dialect, c)).collect();
        lines.push(format!("UNIQUE ({})", cols.join(", ")));
    }
    for check in &table.checks {
        match check.name.as_deref().filter(|n| !n.is_empty()) {
            Some(n) => lines.push(format!("CONSTRAINT {} CHECK ({})", ident(dialect, n), check.expr)),
            None => lines.push(format!("CHECK ({})", check.expr)),
        }
    }
    if with_fks {
        for r in relations.iter().filter(|r| r.kind == RelationKind::Declared && r.from_table == table.name) {
            lines.push(foreign_key(dialect, r));
        }
    }
    let mut out = format!("CREATE TABLE {} (\n  {}\n)", ident(dialect, &table.name), lines.join(",\n  "));
    if dialect == Dialect::MySql
        && let Some(c) = table.comment.as_deref().filter(|c| !c.is_empty())
    {
        let _ = write!(out, " COMMENT={}", quoted(dialect, c));
    }
    out.push_str(";\n");
    if dialect == Dialect::Postgres {
        out.push_str(&pg_comments(table));
    }
    out
}

fn pg_comments(table: &Table) -> String {
    let d = Dialect::Postgres;
    let mut out = String::new();
    if let Some(c) = table.comment.as_deref().filter(|c| !c.is_empty()) {
        let _ = writeln!(out, "COMMENT ON TABLE {} IS {};", ident(d, &table.name), quoted(d, c));
    }
    for col in &table.columns {
        if let Some(c) = col.comment.as_deref().filter(|c| !c.is_empty()) {
            let _ = writeln!(
                out,
                "COMMENT ON COLUMN {}.{} IS {};",
                ident(d, &table.name),
                ident(d, &col.name),
                quoted(d, c)
            );
        }
    }
    out
}

pub fn create_view(dialect: Dialect, view: &Table) -> String {
    let body = view.definition.as_deref().unwrap_or("SELECT 1").trim().trim_end_matches(';');
    format!("CREATE VIEW {} AS {};\n", ident(dialect, &view.name), body)
}

pub fn create_index(dialect: Dialect, table: &str, index: &Index) -> String {
    let cols: Vec<String> = index
        .columns
        .iter()
        // An expression index keeps its text as the server printed it.
        .map(|c| if c.contains(['(', ' ']) { c.clone() } else { ident(dialect, c) })
        .collect();
    let name = if index.name.is_empty() { format!("{table}_{}_idx", index.columns.join("_")) } else { index.name.clone() };
    let kind = index.kind.to_ascii_lowercase();
    let (prefix, using) = match (dialect, kind.as_str()) {
        (Dialect::MySql, "fulltext") => ("FULLTEXT ", String::new()),
        (Dialect::MySql, "spatial") => ("SPATIAL ", String::new()),
        (Dialect::Postgres, k) if !k.is_empty() && k != "btree" => ("", format!(" USING {k}")),
        _ => ("", String::new()),
    };
    format!(
        "CREATE {}{prefix}INDEX {} ON {}{using} ({});\n",
        if index.unique { "UNIQUE " } else { "" },
        ident(dialect, &name),
        ident(dialect, table),
        cols.join(", ")
    )
}

pub fn drop_table(dialect: Dialect, table: &Table) -> String {
    let what = if table.kind == TableKind::View { "VIEW" } else { "TABLE" };
    format!("DROP {what} {};\n", ident(dialect, &table.name))
}

/// PostgreSQL enum types the schema's columns use, as CREATE TYPE.
fn pg_types(schema: &Schema) -> String {
    let mut seen = BTreeSet::new();
    let mut out = String::new();
    for c in schema.tables.iter().flat_map(|t| &t.columns) {
        if let Some(values) = &c.enum_values
            && !c.data_type.to_ascii_lowercase().starts_with("enum(")
            && seen.insert(c.data_type.clone())
        {
            let vals: Vec<String> = values.iter().map(|v| quoted(Dialect::Postgres, v)).collect();
            let _ = writeln!(
                out,
                "CREATE TYPE {} AS ENUM ({});",
                ident(Dialect::Postgres, &c.data_type),
                vals.join(", ")
            );
        }
    }
    out
}

/// The whole schema, in two halves so data can go in between: `before`
/// makes types and tables, `after` adds indexes, foreign keys, views and
/// triggers. SQLite keeps its foreign keys inside CREATE TABLE, since it
/// cannot add them later.
pub struct Script {
    pub before: String,
    pub after: String,
}

impl Script {
    pub fn joined(&self) -> String {
        format!("{}\n{}", self.before, self.after)
    }
}

pub fn schema_script(dialect: Dialect, schema: &Schema) -> Script {
    let mut before = String::new();
    let mut after = String::new();
    if dialect == Dialect::Postgres {
        before.push_str(&pg_types(schema));
    }
    let inline = dialect == Dialect::Sqlite;
    for t in schema.tables.iter().filter(|t| t.kind == TableKind::Table) {
        before.push_str(&create_table(dialect, t, &schema.relations, inline));
        before.push('\n');
        for i in &t.indexes {
            after.push_str(&create_index(dialect, &t.name, i));
        }
    }
    if !inline {
        for r in schema.relations.iter().filter(|r| r.kind == RelationKind::Declared) {
            let _ = writeln!(after, "ALTER TABLE {} ADD {};", ident(dialect, &r.from_table), foreign_key(dialect, r));
        }
    }
    for v in schema.tables.iter().filter(|t| t.kind == TableKind::View) {
        after.push_str(&create_view(dialect, v));
    }
    for t in &schema.tables {
        for trigger in &t.triggers {
            after.push_str(&statement_text(dialect, &trigger.body));
        }
    }
    for r in &schema.routines {
        after.push_str(&statement_text(dialect, &r.definition));
    }
    Script { before, after }
}

/// A trigger or routine as one statement. MariaDB bodies contain `;`, so
/// they are wrapped in `DELIMITER` lines that Atlas' own splitter (and the
/// mysql client) understand.
fn statement_text(dialect: Dialect, text: &str) -> String {
    let text = text.trim();
    if !text.to_ascii_uppercase().starts_with("CREATE") {
        return String::new();
    }
    if dialect == Dialect::MySql && text.contains(';') {
        format!("DELIMITER ;;\n{text} ;;\nDELIMITER ;\n")
    } else {
        format!("{};\n", text.trim_end_matches(';'))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::dump;
    use crate::schema::fixture::shop;
    use crate::schema::{Check, FkAction};

    #[test]
    fn create_table_mysql() {
        let mut s = shop();
        s.relations[0].on_delete = Some(FkAction::Cascade);
        s.relations[0].name = Some("fk_customer".into());
        let orders = s.table("orders").unwrap();
        let sql = create_table(Dialect::MySql, orders, &s.relations, true);
        assert_eq!(
            sql,
            "CREATE TABLE `orders` (\n  `id` int NOT NULL,\n  `customer_id` int NOT NULL,\n  `placed_at` datetime NOT NULL,\n  \
             PRIMARY KEY (`id`),\n  CONSTRAINT `fk_customer` FOREIGN KEY (`customer_id`) REFERENCES `customers` (`id`) ON DELETE CASCADE\n);\n"
        );
    }

    #[test]
    fn sqlite_keeps_the_rowid_alias_and_autoincrement() {
        let mut t = crate::schema::fixture::table(
            "t",
            vec![crate::schema::fixture::col("id", "INTEGER", false, true), crate::schema::fixture::col("n", "int", true, false)],
        );
        t.columns[0].auto_increment = true;
        t.checks.push(Check { name: None, expr: "n > 0".into() });
        assert_eq!(
            create_table(Dialect::Sqlite, &t, &[], true),
            "CREATE TABLE \"t\" (\n  \"id\" INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT,\n  \"n\" int,\n  CHECK (n > 0)\n);\n"
        );
    }

    #[test]
    fn postgres_serial_becomes_identity() {
        let mut c = crate::schema::fixture::col("id", "integer", false, true);
        c.auto_increment = true;
        c.default = Some("nextval('t_id_seq'::regclass)".into());
        assert_eq!(column_def(Dialect::Postgres, &c, false), "\"id\" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL");
    }

    #[test]
    fn indexes() {
        let i = Index { name: "by_name".into(), columns: vec!["name".into()], unique: true, kind: "btree".into() };
        assert_eq!(create_index(Dialect::Postgres, "t", &i), "CREATE UNIQUE INDEX \"by_name\" ON \"t\" (\"name\");\n");
        let g = Index { name: "g".into(), columns: vec!["doc".into()], unique: false, kind: "gin".into() };
        assert_eq!(create_index(Dialect::Postgres, "t", &g), "CREATE INDEX \"g\" ON \"t\" USING gin (\"doc\");\n");
        let f = Index { name: "f".into(), columns: vec!["body".into()], unique: false, kind: "FULLTEXT".into() };
        assert_eq!(create_index(Dialect::MySql, "t", &f), "CREATE FULLTEXT INDEX `f` ON `t` (`body`);\n");
    }

    /// What Atlas writes, Atlas' own dump reader reads back the same.
    #[test]
    fn round_trip_through_the_dump_parser() {
        for dialect in [Dialect::MySql, Dialect::Postgres, Dialect::Sqlite] {
            let mut s = shop();
            s.tables[1].indexes.push(Index {
                name: "orders_placed".into(),
                columns: vec!["placed_at".into()],
                unique: false,
                kind: String::new(),
            });
            s.relations[1].on_delete = Some(FkAction::Cascade);
            let script = schema_script(dialect, &s).joined();
            let (back, report) = dump::parse("shop", &script);
            assert!(report.skipped.is_empty(), "{dialect:?}: {:?}\n{script}", report.skipped);
            assert_eq!(back.tables.len(), s.tables.len(), "{dialect:?}");
            for t in &s.tables {
                let b = back.table(&t.name).unwrap();
                let names = |t: &Table| t.columns.iter().map(|c| (c.name.clone(), c.primary, c.nullable && !c.primary)).collect::<Vec<_>>();
                assert_eq!(names(b), names(t), "{dialect:?} {}", t.name);
                assert_eq!(b.indexes.len(), t.indexes.len(), "{dialect:?} {}", t.name);
            }
            assert_eq!(back.relations.len(), s.relations.len(), "{dialect:?}");
            let r = back.relations.iter().find(|r| r.from_table == "order_lines" && r.from_columns == ["order_id"]).unwrap();
            assert_eq!(r.on_delete, Some(FkAction::Cascade), "{dialect:?}");
        }
    }
}
